interface KanjiItem {
  id: string;
  kanji: string;
  onyomi: string;
  kunyomi: string;
  mongolian: string;
  jlptLevel: 'N4';
  exampleWords: { word: string; reading: string; mongolian: string }[];
  createdAt: string;
}

const lines = rawInput.trim().split('\n');
const kanjiList: KanjiItem[] = [];

lines.forEach((line, index) => {
  if (!line.trim()) return;
  const parts = line.split('|').map(s => s.trim());
  if (parts.length >= 5) {
    const num = parts[0];
    const kanji = parts[1];
    const onyomi = parts[2] || '-';
    const kunyomi = parts[3] || '-';
    const mongolian = parts[4];

    const pad = String(index + 1).padStart(3, '0');
    kanjiList.push({
      id: `k-n4-add-${pad}`,
      kanji,
      onyomi,
      kunyomi,
      mongolian,
      jlptLevel: 'N4',
      exampleWords: [],
      createdAt: '2026-01-01T00:00:00Z'
    });
  }
});

console.log(`Parsed ${kanjiList.length} N4 Kanji items.`);

// 1. Output src/data/n4KanjiAdditions.ts
const tsContent = `import { KanjiItem } from '../types';

export const n4KanjiList: KanjiItem[] = ${JSON.stringify(kanjiList, null, 2)};
`;

fs.writeFileSync(path.join(process.cwd(), 'src/data/n4KanjiAdditions.ts'), tsContent, 'utf-8');
console.log('Saved src/data/n4KanjiAdditions.ts');

// 2. Update data/db.json
const dbPath = path.join(process.cwd(), 'data', 'db.json');
if (fs.existsSync(dbPath)) {
  const dbData = JSON.parse(fs.readFileSync(dbPath, 'utf-8'));
  if (dbData.kanji) {
    const existingIds = new Set(dbData.kanji.map((k: any) => k.id));
    const newItems = kanjiList.filter(k => !existingIds.has(k.id));
    dbData.kanji.push(...newItems);
    fs.writeFileSync(dbPath, JSON.stringify(dbData, null, 2), 'utf-8');
    console.log(`Updated db.json: Total Kanji count: ${dbData.kanji.length}`);
  }
}
