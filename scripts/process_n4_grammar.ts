const tsContent = `import { GrammarItem } from '../types';

export const n4GrammarList: GrammarItem[] = ${JSON.stringify(parsedGrammar, null, 2)};
`;

fs.writeFileSync(path.join(process.cwd(), 'src/data/n4GrammarAdditions.ts'), tsContent, 'utf-8');
