// Split the rawInput by numbered points (1 |, 2 |, etc.)
const itemRegex = /(\d+)\s*\|\s*([^|]+)\s*\|\s*([^|]+)\s*\|\s*([^|]+)\s*\|\s*([^|]+)\s*\|\s*([^|]+?)(?=(?:\s+\d+\s*\||$))/g;

const parsedGrammar: GrammarItem[] = [];
let match: RegExpExecArray | null;

while ((match = itemRegex.exec(rawInput)) !== null) {
  const num = match[1].trim();
  const pattern = match[2].trim();
  const mongolian = match[3].trim().replace(/\s+/g, ' ');
  const exJapanese = match[4].trim().replace(/\s+/g, '');
  const exReading = match[5].trim().replace(/\s+/g, ' ');
  const exMongolian = match[6].trim().replace(/\s+/g, ' ');

  const { usage, structure, explanation } = getGrammarDetails(pattern, mongolian);

  parsedGrammar.push({
    id: `g-n4-add-${num.padStart(3, '0')}`,
    pattern,
    mongolian,
    explanation,
    usage,
    structure,
    examples: [
      {
        japanese: exJapanese,
        reading: exReading,
        mongolian: exMongolian
      }
    ],
    jlptLevel: 'N4',
    createdAt: '2026-01-01T00:00:00Z'
  });
}

console.log(`Parsed ${parsedGrammar.length} N4 Grammar items.`);

